"""
OpenAPI to TypeScript Generator for ScholarPal.
Generates TypeScript interfaces and enums from FastAPI's OpenAPI 3.1 specification,
providing a single source of truth between Python Pydantic models and TypeScript types.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

# Ensure backend root is on sys.path
REPO_ROOT = Path(__file__).resolve().parent.parent
BACKEND_DIR = REPO_ROOT / "backend"
if str(BACKEND_DIR) not in sys.path:
    sys.path.insert(0, str(BACKEND_DIR))

from app.main import create_application


def json_type_to_ts(prop: dict[str, Any], schemas: dict[str, Any]) -> str:
    """Recursively converts a JSON Schema property definition to a TypeScript type string."""
    if "$ref" in prop:
        ref_name = prop["$ref"].split("/")[-1]
        return ref_name

    # Handle anyOf / oneOf unions
    if "anyOf" in prop or "oneOf" in prop:
        sub_schemas = prop.get("anyOf") or prop.get("oneOf") or []
        types: list[str] = []
        for s in sub_schemas:
            if s.get("type") == "null":
                types.append("null")
            else:
                types.append(json_type_to_ts(s, schemas))
        # Deduplicate while preserving order
        unique_types = list(dict.fromkeys(types))
        return " | ".join(unique_types) if unique_types else "any"

    # Handle multi-type array e.g. ["string", "null"]
    p_type = prop.get("type")
    if isinstance(p_type, list):
        types = []
        for t in p_type:
            if t == "null":
                types.append("null")
            elif t == "string":
                types.append("string")
            elif t in ("number", "integer"):
                types.append("number")
            elif t == "boolean":
                types.append("boolean")
            elif t == "array":
                types.append("any[]")
            else:
                types.append("any")
        return " | ".join(list(dict.fromkeys(types)))

    if "enum" in prop:
        enum_vals = prop["enum"]
        return " | ".join(f'"{v}"' if isinstance(v, str) else str(v) for v in enum_vals)

    if p_type == "string":
        return "string"
    if p_type in ("number", "integer"):
        return "number"
    if p_type == "boolean":
        return "boolean"
    if p_type == "array":
        items = prop.get("items", {})
        item_type = json_type_to_ts(items, schemas)
        if " | " in item_type and not item_type.endswith("[]"):
            return f"({item_type})[]"
        return f"{item_type}[]"
    if p_type == "object":
        additional = prop.get("additionalProperties")
        if isinstance(additional, dict):
            val_type = json_type_to_ts(additional, schemas)
            return f"Record<string, {val_type}>"
        if prop.get("properties"):
            # inline object
            lines = ["{"]
            for k, sub_prop in prop["properties"].items():
                t = json_type_to_ts(sub_prop, schemas)
                req = k in prop.get("required", [])
                opt = "" if req else "?"
                lines.append(f"  {k}{opt}: {t};")
            lines.append("}")
            return "\n".join(lines)
        return "Record<string, any>"

    return "any"


def generate_typescript(openapi: dict[str, Any]) -> str:
    schemas: dict[str, Any] = openapi.get("components", {}).get("schemas", {})
    output_lines: list[str] = [
        "/**",
        " * This file was automatically generated by scripts/openapi_to_typescript.py",
        " * DO NOT MODIFY DIRECTLY. To update, run: make generate-types",
        " *",
        " * Source: FastAPI OpenAPI Specification (Pydantic v2 Models & Shared Enums)",
        " */",
        "",
    ]

    # Separate enum schemas and object schemas
    enum_schemas: dict[str, Any] = {}
    interface_schemas: dict[str, Any] = {}

    for name, schema in sorted(schemas.items()):
        if "enum" in schema:
            enum_schemas[name] = schema
        else:
            interface_schemas[name] = schema

    # 1. Output Enums
    output_lines.append(
        "// ==========================================================================="
    )
    output_lines.append("// SHARED ENUMS")
    output_lines.append(
        "// ==========================================================================="
    )
    output_lines.append("")

    for name, schema in enum_schemas.items():
        desc = schema.get("description", "").strip()
        if desc:
            output_lines.append("/**")
            for line in desc.splitlines():
                output_lines.append(f" * {line}")
            output_lines.append(" */")

        enum_members = schema.get("enum", [])
        output_lines.append(f"export enum {name} {{")
        for val in enum_members:
            if isinstance(val, str):
                # Clean key name
                key = val.replace(" ", "_").replace("-", "_").replace(".", "").upper()
                if key[0].isdigit():
                    key = f"_{key}"
                output_lines.append(f'  {key} = "{val}",')
            else:
                output_lines.append(f"  VAL_{val} = {val},")
        output_lines.append("}")
        output_lines.append("")

    # 2. Output Interfaces
    output_lines.append(
        "// ==========================================================================="
    )
    output_lines.append("// DOMAIN SCHEMAS & API OBJECTS")
    output_lines.append(
        "// ==========================================================================="
    )
    output_lines.append("")

    for name, schema in interface_schemas.items():
        desc = schema.get("description", "").strip()
        if desc:
            output_lines.append("/**")
            for line in desc.splitlines():
                output_lines.append(f" * {line}")
            output_lines.append(" */")

        properties = schema.get("properties", {})
        required = set(schema.get("required", []))

        output_lines.append(f"export interface {name} {{")
        for prop_name, prop_def in properties.items():
            prop_desc = prop_def.get("description", "").strip()
            if prop_desc:
                output_lines.append(f"  /** {prop_desc} */")

            ts_type = json_type_to_ts(prop_def, schemas)
            is_req = prop_name in required
            opt_mark = "" if is_req else "?"
            output_lines.append(f"  {prop_name}{opt_mark}: {ts_type};")

        output_lines.append("}")
        output_lines.append("")

    # 3. Export Components Namespace for API Client typing
    output_lines.append(
        "// ==========================================================================="
    )
    output_lines.append("// OPENAPI COMPONENTS WRAPPER")
    output_lines.append(
        "// ==========================================================================="
    )
    output_lines.append("")
    output_lines.append("export interface components {")
    output_lines.append("  schemas: {")
    for name in sorted(schemas.keys()):
        output_lines.append(f"    {name}: {name};")
    output_lines.append("  };")
    output_lines.append("}")
    output_lines.append("")

    return "\n".join(output_lines)


def main() -> None:
    print("1. Generating OpenAPI 3.1 specification from FastAPI backend...")
    app = create_application()
    openapi_dict = app.openapi()

    openapi_path = REPO_ROOT / "openapi.json"
    with open(openapi_path, "w", encoding="utf-8") as f:
        json.dump(openapi_dict, f, indent=2)
    print(f"   -> Wrote OpenAPI spec to {openapi_path}")

    # Also write to frontend/openapi.json
    frontend_openapi = REPO_ROOT / "frontend" / "openapi.json"
    with open(frontend_openapi, "w", encoding="utf-8") as f:
        json.dump(openapi_dict, f, indent=2)
    print(f"   -> Wrote OpenAPI spec to {frontend_openapi}")

    print("2. Generating TypeScript interfaces and enums...")
    ts_code = generate_typescript(openapi_dict)

    types_dir = REPO_ROOT / "frontend" / "src" / "types"
    types_dir.mkdir(parents=True, exist_ok=True)

    ts_path = types_dir / "api.ts"
    with open(ts_path, "w", encoding="utf-8") as f:
        f.write(ts_code)
    print(f"   -> Wrote TypeScript types to {ts_path}")

    # Create index.ts re-exporting api.ts
    index_ts_path = types_dir / "index.ts"
    with open(index_ts_path, "w", encoding="utf-8") as f:
        f.write('export * from "./api";\n')
    print(f"   -> Wrote re-exports to {index_ts_path}")

    print("Type generation completed successfully!")


if __name__ == "__main__":
    main()
